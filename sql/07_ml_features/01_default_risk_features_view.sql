
USE HomeCreditRisk;
GO

CREATE OR ALTER VIEW ml.vw_default_risk_features
AS
SELECT
    -- Application metadata
    a.SK_ID_CURR,
    a.DATASET_TYPE,
    a.TARGET,

    -- Final model features
    a.ANNUITY_CREDIT_RATIO,
    a.DAYS_EMPLOYED,
    a.BUREAU_DEBT_CREDIT_RATIO,

    -- Credit amount / goods price
    CASE
        WHEN a.AMT_GOODS_PRICE > 0
        THEN CAST(a.AMT_CREDIT AS FLOAT)
             / CAST(a.AMT_GOODS_PRICE AS FLOAT)
        ELSE NULL
    END AS CREDIT_GOODS_RATIO,

    a.DAYS_SINCE_MOST_RECENT_BUREAU_CREDIT,
    a.LATE_PAYMENT_RATE,

    -- Previous refusal rate
    CASE
        WHEN a.PREVIOUS_APPLICATION_COUNT > 0
        THEN CAST(a.PREVIOUS_REFUSED_COUNT AS FLOAT)
             / CAST(a.PREVIOUS_APPLICATION_COUNT AS FLOAT)
        ELSE NULL
    END AS PREVIOUS_REFUSAL_RATE,

    a.AGE_YEARS,
    a.TOTAL_ACTUAL_PAYMENT,
    a.AVG_CREDIT_UTILIZATION,

    -- Active bureau credit share
    CASE
        WHEN a.BUREAU_CREDIT_COUNT > 0
        THEN CAST(a.ACTIVE_BUREAU_CREDIT_COUNT AS FLOAT)
             / CAST(a.BUREAU_CREDIT_COUNT AS FLOAT)
        ELSE NULL
    END AS BUREAU_ACTIVE_SHARE,

    a.TOTAL_BUREAU_CREDIT,
    a.AMT_GOODS_PRICE,
    a.MAX_CREDIT_UTILIZATION,
    a.PREVIOUS_APPROVAL_RATE,
    a.ACTIVE_BUREAU_CREDIT_COUNT,
    a.ANNUITY_INCOME_RATIO,
    a.UNDERPAYMENT_RATE,
    a.POS_MONTH_COUNT,
    a.AMT_ANNUITY,
    a.CREDIT_CARD_MONTH_COUNT,
    a.DAYS_SINCE_LAST_PREVIOUS_APPLICATION,
    a.CREDIT_INCOME_RATIO,
    a.TOTAL_BUREAU_OVERDUE,
    a.TOTAL_EXPECTED_PAYMENT,
    a.MAX_PREVIOUS_CREDIT_AMOUNT,
    a.AMT_CREDIT,
    a.AVG_LATE_PAYMENT_DAYS,

    -- Bureau debt / income
    CASE
        WHEN a.AMT_INCOME_TOTAL > 0
        THEN CAST(a.TOTAL_BUREAU_DEBT AS FLOAT)
             / CAST(a.AMT_INCOME_TOTAL AS FLOAT)
        ELSE NULL
    END AS BUREAU_DEBT_INCOME_RATIO,

    a.PAYMENT_EVENT_COUNT,
    a.POS_CONTRACT_COUNT,
    a.NAME_CONTRACT_TYPE,
    a.AVG_PREVIOUS_APPLICATION_AMOUNT,
    a.AMT_INCOME_TOTAL,
    a.MAX_LATE_PAYMENT_DAYS

FROM bi.vw_applicant_overview AS a;
GO



SELECT
    DATASET_TYPE,
    COUNT_BIG(*) AS application_count,
    COUNT_BIG(DISTINCT SK_ID_CURR) AS unique_applicants,
    SUM(
        CASE WHEN TARGET IS NULL THEN 1 ELSE 0 END
    ) AS missing_target
FROM ml.vw_default_risk_features
GROUP BY DATASET_TYPE
ORDER BY DATASET_TYPE;
